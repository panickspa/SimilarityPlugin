    def _build_params_group(self, parent):
        """Parameters / output options group."""
        gb = QGroupBox("Parameters")
        fmt = QFormLayout(gb)
        fmt.setSpacing(4)
        fmt.setContentsMargins(8, 12, 8, 8)

        # Tolerance (repurposed as tolerance for raster, threshold for vector)
        self.lineEditTreshold = QDoubleSpinBox()
        self.lineEditTreshold.setDecimals(4)
        self.lineEditTreshold.setRange(0, 99999)
        self.lineEditTreshold.setValue(85.5555)
        self.lineEditTreshold.setToolTip("Threshold (%%) for vector | Tolerance for raster")
        self.percentLabel = QLabel("%")
        tol_row = QHBoxLayout()
        tol_row.addWidget(self.lineEditTreshold)
        tol_row.addWidget(self.percentLabel)
        fmt.addRow("Threshold:", tol_row)

        # KNN Radius (vector only)
        self.nnRadiusEdit = QDoubleSpinBox()
        self.nnRadiusEdit.setDecimals(4)
        self.nnRadiusEdit.setRange(0, 99999)
        self.nnRadiusEdit.setValue(0.05)
        self.nnRadiusEdit.setEnabled(False)
        fmt.addRow("KNN Radius:", self.nnRadiusEdit)

        # Resampling (raster only — NEW Phase 2)
        self.resamplingCombo = QComboBox()
        self.resamplingCombo.addItems(["Nearest", "Bilinear", "Cubic"])
        self.resamplingCombo.setCurrentIndex(0)  # Nearest
        self.resamplingCombo.setToolTip(
            "Resampling method when raster pixel sizes differ"
        )
        self.resamplingCombo.setEnabled(False)
        fmt.addRow("Resampling:", self.resamplingCombo)

        # Score attribute name (vector only)
        self.attrOutLineEdit = QLineEdit()
        self.attrOutLineEdit.setText("sim_score")
        fmt.addRow("Score attr:", self.attrOutLineEdit)

        # Suffix name (vector only)
        self.sufLineEdit = QLineEdit()
        self.sufLineEdit.setText("SIM_OUT")
        fmt.addRow("Suffix:", self.sufLineEdit)

        # Checkboxes row
        self.diffRasterCheck = QCheckBox("Generate difference raster")
        self.diffRasterCheck.setToolTip(
            "Output a raster showing where the two rasters differ "
            "(raster method only)"
        )
        self.diffRasterCheck.setEnabled(False)
        fmt.addRow("", self.diffRasterCheck)

        parent.addWidget(gb)

